@dataclass(frozen=True)
class RuleSet:
    name: str
    flags: int
    forbidden_types: int  # card types the deck check rejects (EDOPro "lastDuelForbidden")
    description: str


RULES = {
    "mr1": RuleSet("mr1", DUEL_MODE_MR1, DUEL_MODE_MR1_FORB, "Master Rule 1"),
    "mr2": RuleSet("mr2", DUEL_MODE_MR2, DUEL_MODE_MR2_FORB, "Master Rule 2"),
    "mr3": RuleSet("mr3", DUEL_MODE_MR3, DUEL_MODE_MR3_FORB, "Master Rule 3"),
    "mr4": RuleSet("mr4", DUEL_MODE_MR4, DUEL_MODE_MR4_FORB, "Master Rule 4 (New Master Rule)"),
    "mr5": RuleSet("mr5", DUEL_MODE_MR5, DUEL_MODE_MR5_FORB, "Master Rule 5 (Master Rule 2020)"),
    "goat": RuleSet("goat", DUEL_MODE_GOAT, DUEL_MODE_MR1_FORB, "GOAT format"),
    "speed": RuleSet("speed", DUEL_MODE_SPEED, 0, "Speed Duel"),
    "rush": RuleSet("rush", DUEL_MODE_RUSH, 0, "Rush Duel"),
}


def rule_set(name_or_flags: str | int) -> RuleSet:
    """`"mr3"`, `"MR5"`, or raw duel flags (as EDOPro's lastDuelParam) → RuleSet."""
    if isinstance(name_or_flags, int):
        for rs in RULES.values():
            if rs.flags == name_or_flags:
                return rs
        return RuleSet("custom", name_or_flags, 0, f"custom rules {name_or_flags:#x}")
    key = name_or_flags.strip().lower().replace(" ", "")
    if key.isdigit():
        key = "mr" + key
    if key not in RULES:
        raise ValueError(f"unknown rules {name_or_flags!r} (choose from {', '.join(RULES)})")
    return RULES[key]


